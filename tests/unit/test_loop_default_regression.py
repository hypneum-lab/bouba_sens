"""The default AdaptationLoop path is unchanged by the v0.8 probe/control options.

The golden file was generated by ``loop_trace.py`` against ``origin/main``
commit f99f2dc (``src/bouba_sens/loop.py:110-259``), before ``probe_size``
/ ``probe_seed`` / ``capture_seed`` / ``lesion=None`` existed. With none
of the new options passed, the branch must see the same world batches in
the same order and end with a bit-identical COMPLETE state: every entry
of every component found on the loop object (mux, nerve, head, each
sensory encoder: state dict, buffers, parameters, plain attributes),
optimiser state, report contents and the global RNG states. Hashes depend
on platform float kernels, so entry hashes are enforced where torch
version and machine match the golden; the batch log always is.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from tests.unit.loop_trace import trace

GOLDEN = json.loads((Path(__file__).parents[1] / "golden" / "loop_default_main.json").read_text())


def test_golden_provenance_is_pinned() -> None:
    assert GOLDEN["provenance"]["reference_commit"] == "f99f2dc938fafa4584ff37aaad8f2d3a27bc024a"
    assert "loop.py:110-259" in GOLDEN["provenance"]["reference_code"]


REQUIRED_COVERAGE = [
    "opt.state[",  # optimiser moments
    "opt.param_groups",
    "rng.torch",
    "rng.numpy",
    "rng.python",
    ".requires_grad.",
    ".grad.",  # gradients left by the last backward
    "_lesion_log",
    "report.lesion_events",
    "report.transducer_activation_trajectory",
    "report.gate_trajectory",
    "report.codebook_entropy_trajectory",
    "world.attr._proj_audio",
]
LOSS_RTOL = 1e-4  # off-platform only: float kernels may differ in the last bits


def test_golden_covers_required_state() -> None:
    names = list(GOLDEN["entries"])
    missing = [pat for pat in REQUIRED_COVERAGE if not any(pat in n for n in names)]
    assert not missing, f"golden lacks entries for: {missing}"


def test_default_path_matches_main() -> None:
    got = trace()
    assert [list(c) for c in got["pretrain_calls"]] == GOLDEN["pretrain_calls"]  # type: ignore[attr-defined]
    assert [list(c) for c in got["lesion_calls"]] == GOLDEN["lesion_calls"]  # type: ignore[attr-defined]
    same_platform = (got["torch"], got["machine"]) == (GOLDEN["torch"], GOLDEN["machine"])
    # Losses are always compared: exactly on the golden platform, else to LOSS_RTOL.
    if same_platform:
        assert got["loss_curve"] == GOLDEN["loss_curve"]
    else:
        assert got["loss_curve"] == pytest.approx(GOLDEN["loss_curve"], rel=LOSS_RTOL)
        pytest.skip("entry hashes were generated on a different torch/machine")
    entries: dict[str, str] = got["entries"]  # type: ignore[assignment]
    ref: dict[str, str] = GOLDEN["entries"]
    assert set(entries) == set(ref), sorted(set(entries) ^ set(ref))[:5]
    for name in ref:  # insertion order = discovery order, so the first diff is reported
        assert entries[name] == ref[name], f"first differing entry: {name}"


def test_batch_sizes_unchanged_by_default() -> None:
    """Probe stays at batch_size and seed - 99_999 when no new option is passed."""
    calls = GOLDEN["lesion_calls"]
    assert calls[0] == [4, 50 - 99_999]
    assert all(bs == 4 for bs, _ in calls)
