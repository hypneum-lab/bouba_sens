"""The default AdaptationLoop path is unchanged by later, opt-in options.

The golden file was generated by ``loop_trace.py`` against ``origin/main``
commit 6ae1daa (``src/bouba_sens/loop.py:163-362``) on the reference
platform recorded in the file (torch, machine, nerve-wml). It supersedes the
f99f2dc golden (2026-10-24), which predated ``SensoryWML.emission`` (4e1dffc)
and the nerve-wml v1.8.1 sibling; see issue #96 for the key-level diff. With
none of the opt-in options passed, the branch must see the same world batches
in the same order and end with a bit-identical COMPLETE state: every entry of
every component found on the loop object (mux, nerve, head, each sensory
encoder: state dict, buffers, parameters, plain attributes), optimiser state,
report contents and the global RNG states. Hashes depend on platform float
kernels and on the traced attribute set, so entry hashes are enforced only
where torch version, machine and nerve-wml version all match the golden; the
batch log and the loss curve always are. CI runs this file on ``macos-15``
(arm64) so the reference platform is covered and the skip stays visible.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from tests.unit.loop_trace import trace

GOLDEN = json.loads((Path(__file__).parents[1] / "golden" / "loop_default_main.json").read_text())


def test_golden_provenance_is_pinned() -> None:
    assert GOLDEN["provenance"]["reference_commit"] == "6ae1daad5c4c21a18f38c6b83bc325f93585d09a"
    assert "loop.py:163-362" in GOLDEN["provenance"]["reference_code"]
    assert GOLDEN["provenance"]["supersedes"]["reference_commit"].startswith("f99f2dc")
    assert GOLDEN["nerve_wml"] == "1.8.1"


REQUIRED_COVERAGE = [
    "opt.state[",  # optimiser moments
    "opt.param_groups",
    "rng.torch",
    "rng.numpy",
    "rng.python",
    ".requires_grad.",
    ".grad.",  # gradients left by the last backward
    "_lesion_log",
    "report.lesion_events",
    "report.transducer_activation_trajectory",
    "report.gate_trajectory",
    "report.codebook_entropy_trajectory",
    "world.attr._proj_audio",
]
LOSS_RTOL = 1e-4  # off-platform only: float kernels may differ in the last bits


def test_golden_covers_required_state() -> None:
    names = list(GOLDEN["entries"])
    missing = [pat for pat in REQUIRED_COVERAGE if not any(pat in n for n in names)]
    assert not missing, f"golden lacks entries for: {missing}"


def test_default_path_matches_main() -> None:
    got = trace()
    assert [list(c) for c in got["pretrain_calls"]] == GOLDEN["pretrain_calls"]  # type: ignore[attr-defined]
    assert [list(c) for c in got["lesion_calls"]] == GOLDEN["lesion_calls"]  # type: ignore[attr-defined]
    same_platform = (got["torch"], got["machine"], got["nerve_wml"]) == (
        GOLDEN["torch"],
        GOLDEN["machine"],
        GOLDEN["nerve_wml"],
    )
    # Losses are always compared: exactly on the golden platform, else to LOSS_RTOL.
    if same_platform:
        assert got["loss_curve"] == GOLDEN["loss_curve"]
    else:
        assert got["loss_curve"] == pytest.approx(GOLDEN["loss_curve"], rel=LOSS_RTOL)
        pytest.skip(
            f"entry hashes were generated on torch {GOLDEN['torch']} / {GOLDEN['machine']} / "
            f"nerve-wml {GOLDEN['nerve_wml']}; here {got['torch']} / {got['machine']} / "
            f"{got['nerve_wml']}"
        )
    entries: dict[str, str] = got["entries"]  # type: ignore[assignment]
    ref: dict[str, str] = GOLDEN["entries"]
    assert set(entries) == set(ref), sorted(set(entries) ^ set(ref))[:5]
    for name in ref:  # insertion order = discovery order, so the first diff is reported
        assert entries[name] == ref[name], f"first differing entry: {name}"


def test_batch_sizes_unchanged_by_default() -> None:
    """Probe stays at batch_size and seed - 99_999 when no new option is passed."""
    calls = GOLDEN["lesion_calls"]
    assert calls[0] == [4, 50 - 99_999]
    assert all(bs == 4 for bs, _ in calls)
